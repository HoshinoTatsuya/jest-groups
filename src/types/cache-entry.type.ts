import type { Estimator } from './estimator.type';

/**
 * Факт о файле спеки из прошлого прогона. Свеж, только пока у файла те же
 * `mtimeMs` и `size`, что были ДО прогона, давшего факт: правка после него —
 * и число планируется заново (`plannedTests`): факт, рост по тексту с
 * калибровкой этого файла, рост размера.
 */
export interface CacheEntry {
  readonly tests: number;
  readonly mtimeMs: number;
  readonly size: number;
  /** Время выполнения файла в прошлом прогоне, мс (из отчёта); нет — неизвестно. */
  readonly durationMs?: number;
  /**
   * Оценка по тексту ТОГО ЖЕ содержимого, что дало факт (без запаса). Пара
   * «факт / оценка» калибрует оценку файла: правка, добавившая k видимых
   * тестов, планируется как k × (факт / оценка), а не как k. Нет — запись до
   * 0.6.0.
   */
  readonly estimate?: number;
  /**
   * Оценщик `estimate`. Оценка другого оценщика (проект перешёл на
   * TypeScript 7 без typescript6 или поставил его) не калибрует: прежде
   * «факт 8 / регулярка 1» умножал прирост, видимый AST, в 8 раз. Нет — запись
   * до 0.6.1: считается оценкой ТЕКУЩЕГО оценщика (так было у всех, кроме
   * проектов на TypeScript 7, которые до 0.6.1 не запускались вовсе).
   */
  readonly estimator?: Estimator;
}
