/**
 * Оценка числа тестов файла по тексту. `certain: false` — текст числа не
 * показывает: тест внутри повтора неизвестной длины (таблица из импорта,
 * цикл с условием) или ни одного видимого вызова теста (тесты строит
 * помощник). Такой оценке нельзя верить даже с запасом.
 */
export interface TestAssessment {
  readonly tests: number;
  readonly certain: boolean;
}
