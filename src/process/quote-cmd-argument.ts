/**
 * Аргумент для строки `cmd.exe /d /s /c "…"`. Кавычки сами по себе cmd.exe не
 * защищают: `%VAR%` раскрывается и внутри них, `!VAR!` — при включённом
 * отложенном раскрытии, `&`/`|` за пределами пары кавычек рвут команду. Поэтому
 * сначала — правила разбора argv программой (обратные слэши перед кавычкой
 * удваиваются, кавычка экранируется `\\"`), затем кавычки вокруг, затем `^`
 * перед КАЖДЫМ метасимволом, включая сами кавычки. Обёртка `.cmd` (bin в
 * node_modules) передаёт аргументы дальше через `%*`, то есть cmd разбирает
 * строку второй раз — экранирование нужно двойное (`doubleEscape`).
 *
 * Те же правила, что у широко используемого порта spawn для Windows; на
 * настоящем Windows не проверено — проверены выходные строки.
 */
export const quoteCmdArgument = (arg: string, doubleEscape: boolean): string => {
  // Метасимволы cmd.exe: каждый экранируется `^`, иначе cmd разберёт его сам.
  const CMD_META = /([()\][%!^"`<>&|;, *?])/g;
  let quoted = arg.replace(/(\\*)"/g, '$1$1\\"').replace(/(\\*)$/, '$1$1');
  quoted = `"${quoted}"`.replace(CMD_META, '^$1');
  return doubleEscape ? quoted.replace(CMD_META, '^$1') : quoted;
};
