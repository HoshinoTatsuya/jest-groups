/**
 * Адресует ли pid ровно один процесс или одну группу: целое, по модулю больше 1.
 * Для `kill()` остальные значения не означают «никого»: `-1` — ВСЕ процессы,
 * которым вызывающий вправе слать сигнал, `0` — своя группа (сам раннер),
 * `1` — init/launchd. 16.11.2026 сентинел `pid ?? -1` в соседней библиотеке
 * под мутантом разослал SIGTERM всем процессам пользователя: закрылись все
 * приложения, VPN и Docker.
 */
export const isSignalablePid = (pid: number): boolean => Number.isSafeInteger(pid) && Math.abs(pid) > 1;
