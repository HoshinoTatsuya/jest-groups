import { findLastJson } from './find-last-json';

/**
 * Выборка из вывода `jest --listTests --json`: ПОСЛЕДНИЙ массив строк, который
 * начинается с новой строки. Сам jest печатает его одной строкой, но команда
 * после `--` бывает обёрткой, и обёртка печатает массив с отступами, по строке
 * на элемент: построчный поиск видел в нём только `[` и отвечал «списка нет».
 * Перед массивом бывают строки обёртки (`pnpm run` печатает заголовок), после —
 * строки журнала, поэтому ищется с конца. Массив — только с начала строки: `[`
 * внутри строки (путь `app/[id]/…` в однострочном выводе) началом не считается,
 * иначе `[]` из пути читался бы пустой выборкой. `null` — списка нет: это отказ,
 * а не пустая выборка.
 */
export const parseListTestsOutput = (stdout: string): string[] | null =>
  findLastJson(
    stdout,
    '[',
    (value): value is string[] => Array.isArray(value) && value.every((item) => typeof item === 'string'),
  );
